"""
Generates the specification files shared by every library:

    spec/cipher_tables.json   substitution tables (password, decode) + sin table
    spec/test_vectors.json    DMX universe -> expected scrambled frame (byte for byte)

The ONLY source is tools/reference/cipher_reference.py: the Python port of Code.java
(RY-AI Android app) whose frames were validated on the real interface (blink test).
Every library (Python, C, C#, Java) is tested against these vectors: if a library
produces the same bytes, it talks to the interface exactly like the original app.

Usage:  python tools/generate_spec.py
"""

import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent / "reference"))

import cipher_reference as ref  # noqa: E402

FRAME_LEN = 521
UNIVERSE_SIZE = 512
PAYLOAD_START = 5
MARKER_OFFSET = 517


def build_reference_frame(universe, code_num, scene=0, speed=0):
    """Builds a frame with the reference implementation.

    universe: 512 values, index 0 = DMX channel 1.
    """
    buf = bytearray(FRAME_LEN)
    buf[0] = 0x00
    buf[1], buf[2] = ord("K"), ord("T")      # start marker
    buf[3], buf[4] = scene, speed
    buf[PAYLOAD_START:PAYLOAD_START + UNIVERSE_SIZE] = bytes(universe)
    buf[519], buf[520] = ord("T"), ord("K")  # end marker
    return ref.encryption1(buf, PAYLOAD_START, UNIVERSE_SIZE, code_num, MARKER_OFFSET)


def universe_from(channels):
    """Builds a universe from a dict {DMX channel (1..512): value}; other channels are 0."""
    universe = [0] * UNIVERSE_SIZE
    for channel, value in channels.items():
        universe[channel - 1] = value
    return universe


def test_cases():
    """(name, description, universe, code_num) of every test vector."""
    rng = random.Random(2026)
    return [
        ("all_zeros_code0", "Empty universe.", [0] * UNIVERSE_SIZE, 0),

        ("reference_code1",
         "Channel 1=255, 2=128, 3=1, 14=42, 512=7 (same frame as the DmxCtrl app tests).",
         universe_from({1: 255, 2: 128, 3: 1, 14: 42, 512: 7}), 1),

        ("ramp_code42", "Channel n = (n * 7) mod 256.",
         [(n * 7) % 256 for n in range(1, UNIVERSE_SIZE + 1)], 42),

        ("all_full_code128", "Every channel at 255.", [255] * UNIVERSE_SIZE, 128),

        ("random_code255", "Pseudo-random values (seed 2026).",
         [rng.randrange(256) for _ in range(UNIVERSE_SIZE)], 255),

        ("mindi_spider_address1_code7",
         "Mini Spider set to address 1 (it listens from channel 2): mirrored wings at 200, "
         "dimmer 100 %, LED 1 and LED 5 at full.",
         universe_from({2: 200, 3: 55, 4: 255, 6: 255, 10: 255}), 7),

        ("chauvet_spot260x_two_heads_code9",
         "Two Intimidator Spot 260X in 14-channel mode. Head at address 17: pan 0x8000, tilt 0x4000, "
         "red, gobo 3, gobo rotation clockwise speed 128, prism on, focus 128, dimmer 255, shutter open. "
         "Head at address 31: pan 0x8000, tilt 0x4000, blue, no gobo, focus 128, dimmer 255, strobe speed 128.",
         universe_from({
             # head 1, address 17
             17: 128, 19: 64, 22: 10, 23: 27, 24: 63, 25: 255, 26: 128, 27: 255, 28: 255,
             # head 2, address 31
             31: 128, 33: 64, 36: 38, 37: 3, 40: 128, 41: 255, 42: 42,
         }), 9),
    ]


def vectors():
    """Turns every test case into a JSON-ready dict with the expected frame."""
    out = []
    for name, description, universe, code_num in test_cases():
        frame = build_reference_frame(universe, code_num)
        out.append({
            "name": name,
            "description": description,
            "code_num": code_num,
            "scene": 0,
            "speed": 0,
            "universe_hex": bytes(universe).hex(),
            "frame_hex": bytes(frame).hex(),
        })
    return out


def write_cipher_tables(spec_dir):
    tables = {
        "_comment": "Scrambling tables of the JL_SPP DMX protocol (Code.java of the RY-AI app). "
                    "password[k][v] = scrambled byte; decode[k] = inverse permutation of password[k]; "
                    "sin = 256-value table (table choice: sin[codeNum] % 5).",
        "password": ref.password,
        "decode": ref.decode,
        "sin": ref.sin,
    }
    (spec_dir / "cipher_tables.json").write_text(json.dumps(tables, indent=1), encoding="utf-8")


def write_test_vectors(spec_dir):
    data = {
        "_comment": "Test vectors: universe (512 bytes, index 0 = DMX channel 1) -> expected 521-byte frame. "
                    "Generated by tools/generate_spec.py from the implementation validated on the hardware.",
        "frame_length": FRAME_LEN,
        "universe_size": UNIVERSE_SIZE,
        "handshake_connect_hex": "bb9977017799",
        "handshake_disconnect_hex": "bb77991099770055",
        "vectors": vectors(),
    }
    (spec_dir / "test_vectors.json").write_text(json.dumps(data, indent=1, ensure_ascii=False), encoding="utf-8")
    return len(data["vectors"])


def main():
    spec_dir = ROOT / "spec"
    spec_dir.mkdir(exist_ok=True)
    write_cipher_tables(spec_dir)
    count = write_test_vectors(spec_dir)
    print(f"spec/cipher_tables.json and spec/test_vectors.json ({count} vectors) generated.")


if __name__ == "__main__":
    main()
